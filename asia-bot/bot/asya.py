def get_random_fact() -> str:
    """Return a random Asya fact about herself or cars."""
    return random.choice(ASYA_FACTS)


def get_random_interest() -> tuple:
    """Get a random (interest, item) pair for personality / discovery generation."""
    interest = random.choice(list(ASYA_INTERESTS.keys()))
    item = random.choice(ASYA_INTERESTS[interest])
    return interest, item


def get_random_word(category: str = "agreement") -> str:
    """Get a random Asya vocabulary word from the given category."""
    words = ASYA_WORDS.get(category, ASYA_WORDS["agreement"])
    return random.choice(words)


def get_car_problems(brand: str) -> Optional[Dict]:
    """Return common problems, engines and tips for a car brand.

    Args:
        brand: Car brand name (case-insensitive), e.g. "BMW", "volkswagen".

    Returns:
        Dict with keys 'common', 'engines', 'tips' or None if brand unknown.
    """
    # First try exact match, then case-insensitive
    brand = brand.strip()
    if brand in CAR_PROBLEMS_DB:
        return CAR_PROBLEMS_DB[brand]
    brand_lower = brand.lower()
    for key in CAR_PROBLEMS_DB:
        if key.lower() == brand_lower:
            return CAR_PROBLEMS_DB[key]
    return None


def get_engine_info(brand: str, engine_code: str) -> Optional[str]:
    """Return a human-readable description for a specific engine.

    Args:
        brand: Car brand name (case-insensitive).
        engine_code: Engine code (case-insensitive), e.g. "N63", "ea888 gen3".

    Returns:
        Description string or None if not found.
    """
    brand_data = get_car_problems(brand)
    if not brand_data:
        return None
    engines = brand_data.get("engines", {})
    engine_code_upper = engine_code.upper()
    for code, info in engines.items():
        if code.upper() == engine_code_upper:
            return info
    return None


def get_obd2_description(code: str) -> Optional[str]:
    """Return a human-readable description for an OBD2 error code.

    Args:
        code: OBD2 code (case-insensitive), e.g. "P0420", "p0171".

    Returns:
        Description string or None if code unknown.
    """
    code = code.upper().strip()
    return OBD2_CODES.get(code)
